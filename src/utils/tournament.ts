export function createTeams(count: number, customNames?: string[]): Team[] {
  return Array.from({ length: count }, (_, idx) => {
    const preset = DEFAULT_TEAM_PRESETS[idx % DEFAULT_TEAM_PRESETS.length];
    return {
      id: `team-${idx + 1}`,
      name: customNames?.[idx]?.trim() || preset.name,
      colorIndex: preset.colorIndex,
      mascot: preset.mascot,
      totalPoints: 0,
      matchesPlayed: 0,
      wins: 0,
      losses: 0,
      draws: 0,
      totalCorrect: 0,
      totalAnswered: 0,
      bestStreak: 0,
      eliminated: false,
    };
  });
}

